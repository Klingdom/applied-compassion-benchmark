const PAID_HREF = /gumroad\.com|\/pricing\b|\/contact-sales\b|\/purchase-research\b|\/advisory\b|\/enterprise\b|\/data-licenses\b|\/certified-assessments\b|\/score-watch\b|\/supporters\b|\/api-access\b|twitter\.com\/intent|x\.com\/intent|facebook\.com\/sharer|linkedin\.com\/share/i;
const URGENCY = /before it'?s too late|see which ai fails|risk alert|countdown|limited time|act now|don'?t miss/i;

/**
 * Template H over <main> of a report page. (The global Navbar and Footer sit outside <main>; they carry
 * site-wide services links that this page does not author. Reported in the handoff.)
 */
export function ctaProblems(html) {
  const p = [];
  const main = html.match(/<main\b[\s\S]*<\/main>/i)?.[0] ?? html;
  for (const m of main.matchAll(/\bhref="([^"]*)"/gi)) if (PAID_HREF.test(m[1])) p.push(`H-paid-link: the report article links to ${m[1]}`);
  const text = textBlocks(main).join("\n");
  if (/score-?watch/i.test(text)) p.push("H-score-watch: the report article mentions Score-Watch");
  if (URGENCY.test(text)) p.push("H-urgency: urgency copy in the report article");
  if (/mailto:[^"]*\bbody=/i.test(main)) p.push("H-prefill: a mailto link carries prefilled body text");
  // Only one primary button per surface: the Button component's primary variant carries this gradient.
  const primaries = (main.match(/from-accent to-accent-2/g) ?? []).length;
  if (primaries > 1) p.push(`H-primary: ${primaries} primary buttons in the report article (one per surface)`);
  return p;
}
