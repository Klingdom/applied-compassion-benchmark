const metaContent = (html, attr, name) => {
  const m = html.match(new RegExp(`<meta\\b[^>]*\\b${attr}="${escRe(name)}"[^>]*>`, "i"));
  const c = m?.[0].match(/\bcontent="([^"]*)"/i);
  return c ? decode(c[1]) : null;
};

const LEADERBOARD_TERMS = /\b(?:top|best|worst|leads?|beats?|wins?|rank(?:s|ed|ing)?|leaderboard|#1|most compassionate|least compassionate|scorecard results)\b/i;

/**
 * G20 over one built report page. `expected` = { runId, title } from the site's own rules
 * (reportTitle) so the test does not retype copy.
 */
export function seoProblems({ html, wave, expected }) {
  const p = [];
  const naming = makeNaming(wave);
  const lex = (label, text) => { for (const q of lexiconProblems(text, wave)) p.push(`G20-lexicon (${label}): ${q.rule}: ${q.message}`); };
  const url = `${SITE_URL}/ai-models/reports/${wave.run_id}`;

  const head = html.split(/<\/head>/i)[0];
  const titles = [...head.matchAll(/<title\b[^>]*>([\s\S]*?)<\/title>/gi)].map((m) => decode(m[1]));
  if (titles.length !== 1) p.push(`G20-title: expected exactly one <title>, found ${titles.length}`);
  const title = titles[0] ?? "";
  if (!/^Unofficial Pilot:/.test(title)) p.push(`G20-title: the title must start with the status words "Unofficial Pilot:" (got "${title.slice(0, 60)}")`);
  if (expected?.title && title !== expected.title) p.push(`G20-title: "${title}" differs from the title built from the wave ("${expected.title}")`);
  if (naming.mentions(title).length) p.push("G20-title: the title names a model");
  if (/\d/.test(title.replace(/\((?:[A-Z][a-z]{2}) \d{4}\)/, ""))) p.push("G20-title: the title carries a number beyond the month and year");
  lex("title", title);

  const desc = metaContent(html, "name", "description");
  if (!desc) p.push("G20-meta: no meta description");
  else {
    lex("meta description", desc);
    p.push(...figureTokenProblems("meta description", desc, wave));
    if (naming.mentions(desc).length) p.push("G20-meta: the meta description names a model");
  }

  const canon = [...html.matchAll(/<link\b[^>]*\brel="canonical"[^>]*>/gi)].map((m) => m[0].match(/\bhref="([^"]*)"/i)?.[1]);
  if (canon.length !== 1) p.push(`G20-canonical: expected exactly one canonical link, found ${canon.length}`);
  else if (canon[0] !== url) p.push(`G20-canonical: "${canon[0]}" is not the absolute self-URL ${url}`);
  const robots = metaContent(html, "name", "robots");
  if (robots && /noindex/i.test(robots)) p.push(`G20-robots: the report is noindex ("${robots}"); template G: indexable`);

  for (const k of ["og:title", "og:description"]) {
    const v = metaContent(html, "property", k);
    if (!v) p.push(`G20-og: ${k} missing`);
    else { lex(k, v); p.push(...figureTokenProblems(k, v, wave)); }
  }
  const ogUrl = metaContent(html, "property", "og:url");
  if (ogUrl && ogUrl !== url) p.push(`G20-og: og:url "${ogUrl}" is not ${url}`);
  const ogAlt = metaContent(html, "property", "og:image:alt");
  if (ogAlt) { lex("og:image:alt", ogAlt); p.push(...figureTokenProblems("og:image:alt", ogAlt, wave)); }
  for (const k of ["twitter:title", "twitter:description"]) {
    const v = metaContent(html, "name", k);
    if (v) { lex(k, v); p.push(...figureTokenProblems(k, v, wave)); }
  }

  // JSON-LD
  const blocks = extractJsonLd(html);
  const nodes = [];
  for (const b of blocks) walk(b, (o) => nodes.push(o));
  const reports = nodes.filter((o) => [].concat(o["@type"] ?? []).includes("Report"));
  if (reports.length !== 1) p.push(`G20-jsonld: expected exactly one Report node, found ${reports.length}`);
  const rep = reports[0];
  if (rep) {
    if (rep.headline !== title) p.push(`G20-jsonld: Report.headline "${String(rep.headline).slice(0, 60)}" differs from <title>`);
    if (!/unofficial/i.test(String(rep.creativeWorkStatus ?? ""))) p.push("G20-jsonld: Report.creativeWorkStatus does not say unofficial");
    if (rep.reportNumber !== wave.run_id) p.push(`G20-jsonld: Report.reportNumber "${rep.reportNumber}" is not the run id`);
    if (!String(rep.isBasedOn ?? "").endsWith(`/data/model-waves/${wave.run_id}.json`)) p.push(`G20-jsonld: Report.isBasedOn "${rep.isBasedOn}" is not the wave file URL`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(String(rep.datePublished ?? ""))) p.push("G20-jsonld: Report.datePublished missing or not a date");
    if ("sameAs" in rep) p.push("G20-jsonld: Report carries sameAs (a model identity link is forbidden)");
  }
  if (!nodes.some((o) => [].concat(o["@type"] ?? []).includes("BreadcrumbList"))) p.push("G20-jsonld: no BreadcrumbList");
  const textBody = textBlocks(html).join("\n");
  for (const n of nodes.filter((o) => [].concat(o["@type"] ?? []).includes("Question"))) {
    if (!textBody.includes(String(n.name ?? "").slice(0, 40))) p.push(`G20-jsonld: FAQPage question "${String(n.name).slice(0, 50)}" is not visible on the page`);
  }
  for (const n of nodes) {
    if ("sameAs" in n && !([].concat(n["@type"] ?? []).some((t) => /Organization/.test(t)))) p.push(`G20-jsonld: a non-Organization node carries sameAs (${[].concat(n["@type"] ?? []).join(",")})`);
  }
  // Every JSON-LD string except the Organization nodes' own descriptions goes through the lexicon and the figure scan.
  for (const { key, text, node } of jsonLdStrings(blocks)) {
    if ([].concat(node["@type"] ?? []).some((t) => /Organization|WebSite|ImageObject/.test(t))) continue;
    if (/^(?:@|url|item|mainEntityOfPage|isBasedOn|isPartOf|inLanguage|datePublished|dateCreated|reportNumber)$/.test(key)) continue;
    lex(`JSON-LD ${key}`, text);
    p.push(...figureTokenProblems(`JSON-LD ${key}`, text, wave));
  }

  // Leaderboard terms within 60 characters of a model name in headings, captions, alt text and JSON-LD.
  const near = (label, text) => {
    for (const m of naming.mentions(text)) {
      const win = text.slice(Math.max(0, m.start - 60), m.end + 60);
      const hit = win.match(LEADERBOARD_TERMS);
      if (hit && !/\b(?:not|no|never|cannot)\b[^.]{0,40}\b(?:rank|ranking|leaderboard)/i.test(win)) p.push(`G20-near-model: "${hit[0]}" within 60 characters of a model name in ${label}: "${win.slice(0, 90)}"`);
    }
  };
  for (const m of html.matchAll(/<(h[1-3]|figcaption|caption)\b[^>]*>([\s\S]*?)<\/\1>/gi)) near(m[1], cellText(m[2]));
  for (const t of attributeTexts(html)) near("an attribute (alt/aria-label/title)", t);
  for (const { text } of jsonLdStrings(blocks)) near("JSON-LD", text);

  // Document structure: one H1.
  const h1s = (html.match(/<h1\b/gi) ?? []).length;
  if (h1s !== 1) p.push(`G20-structure: expected one <h1>, found ${h1s}`);
  // Links to or from AI Labs entity pages and the homepage/rankings (template G).
  const main = html.match(/<main\b[\s\S]*<\/main>/i)?.[0] ?? html;
  if (/href="\/ai-lab\//i.test(main)) p.push("G20-links: the report links to an AI Labs entity page (D-23: lab and model scores are never fused)");
  return p;
}

/** Meta and OG carry no per-model figure (template G). */
export function figureTokenProblems(label, text, wave) {
  const p = [];
  const w = withheldValues(wave);
  for (const tok of [...w.allComposites, ...w.allIntervalEnds, ...w.bounds]) if (tokRe(tok).test(text)) p.push(`G20-figure: ${tok} (a per-model figure) in ${label}`);
  for (const band of BAND_NAMES) if (new RegExp(`\\b${band}\\b`).test(text)) p.push(`G20-band: band name "${band}" in ${label}`);
  return p;
}

/** Sitemap: one entry per rendered report, changefreq never, lastmod the report date. */
export function sitemapProblems(xml, manifest, env) {
  const p = [];
  for (const { entry } of renderableEntries(manifest, env)) {
    const m = xml.match(new RegExp(`<url>(?:(?!</url>)[\\s\\S])*?${escRe(`${SITE_URL}/ai-models/reports/${entry.run_id}`)}(?:(?!</url>)[\\s\\S])*?</url>`));
    if (!m) { p.push(`G20-sitemap: no sitemap entry for /ai-models/reports/${entry.run_id}`); continue; }
    if (!/<changefreq>never<\/changefreq>/.test(m[0])) p.push(`G20-sitemap: ${entry.run_id} changefreq is not "never"`);
    if (!m[0].includes(`<lastmod>${entry.report_date}`)) p.push(`G20-sitemap: ${entry.run_id} lastmod is not the report date ${entry.report_date}`);
  }
  return p;
}

