export function extractJsonLd(html) {
  const out = [];
  for (const m of html.matchAll(/<script[^>]*type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script>/gi)) {
    try { out.push(JSON.parse(m[1])); } catch { out.push({ "@parseError": m[1].slice(0, 60) }); }
  }
  return out;
}

function walk(x, visit) {
  if (Array.isArray(x)) x.forEach((v) => walk(v, visit));
  else if (x && typeof x === "object") {
    visit(x);
    Object.values(x).forEach((v) => walk(v, visit));
  }
}

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", rsquo: "’", lsquo: "‘", ldquo: "“", rdquo: "”", mdash: "—", ndash: "–", middot: "·", hellip: "…", rarr: "→", minus: "−" };
export function decode(s) {
  return s
    .replace(/&#x([0-9a-f]+);/gi, (_m, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_m, d) => String.fromCodePoint(Number(d)))
    .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m);
}

const BLOCK_TAGS = "p|li|td|th|h[1-6]|figcaption|caption|tr|summary|dt|dd|text|title|desc|aside|div|section|article|header|footer|nav|details|figure|ul|ol|table|thead|tbody|main|body|blockquote|button|label";

/** Strip comments, scripts and styles; keep JSON-LD separately. */
function bare(html) {
  return html
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "")
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, "");
}

/** Text blocks: text between block-level tag boundaries. Inline tags (a, span, strong, tspan...) do not split. */
export function textBlocks(html) {
  return decode(
    bare(html)
      .replace(new RegExp(`</?(?:${BLOCK_TAGS})\\b[^>]*>`, "gi"), "\u0001")
      .replace(/<[^>]+>/g, ""),
  )
    .split("\u0001")
    .map((t) => t.replace(/\s+/g, " ").trim())
    .filter(Boolean);
}

/** Attribute text a reader or tool can see: aria-label, alt, title, meta content. */
export function attributeTexts(html) {
  const out = [];
  for (const m of bare(html).matchAll(/\b(?:aria-label|alt|title|content)="([^"]*)"/gi)) out.push(decode(m[1]));
  return out;
}

export function jsonLdStrings(blocks) {
  const out = [];
  for (const b of blocks) walk(b, (o) => { for (const [k, v] of Object.entries(o)) if (typeof v === "string") out.push({ key: k, text: v, node: o }); });
  return out;
}

const cellText = (inner) => decode(inner.replace(/<!--[\s\S]*?-->/g, "").replace(/<[^>]+>/g, "")).replace(/\s+/g, " ").trim();

/**
 * Tables with a real header grid. Returns
 * [{ figure, caption, headers: [string per column], rows: [[{text, header}]] }]
 */
export function parseTables(html) {
  const src = html.replace(/<!--[\s\S]*?-->/g, "");
  const figures = [...src.matchAll(/<figure\b[^>]*\bid="([^"]+)"[^>]*>/gi)].map((m) => ({ id: m[1], start: m.index, end: src.indexOf("</figure>", m.index) }));
  const tables = [];
  for (const tm of src.matchAll(/<table\b[^>]*>([\s\S]*?)<\/table>/gi)) {
    const inner = tm[1];
    const fig = figures.find((f) => tm.index > f.start && tm.index < f.end)?.id ?? null;
    const caption = cellText(inner.match(/<caption\b[^>]*>([\s\S]*?)<\/caption>/i)?.[1] ?? "");
    const trs = [...inner.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi)].map((m) => ({ inner: m[1], index: m.index }));
    const theadEnd = inner.search(/<\/thead>/i);
    const hasThead = theadEnd >= 0;
    const rowsRaw = trs.map((r) => ({
      inHead: hasThead ? r.index < theadEnd : false,
      cells: [...r.inner.matchAll(/<(t[hd])\b([^>]*)>([\s\S]*?)<\/\1>/gi)].map((c) => ({
        tag: c[1].toLowerCase(),
        colspan: Number(c[2].match(/colspan="?(\d+)/i)?.[1] ?? 1),
        rowspan: Number(c[2].match(/rowspan="?(\d+)/i)?.[1] ?? 1),
        text: cellText(c[3]),
      })),
    }));
    if (!hasThead && rowsRaw.length && rowsRaw[0].cells.some((c) => c.tag === "th")) rowsRaw[0].inHead = true;
    // Place every cell in a grid honouring rowspan and colspan.
    const grid = [];
    const occupied = new Map();
    rowsRaw.forEach((row, r) => {
      grid[r] = [];
      let c = 0;
      for (const cell of row.cells) {
        while (occupied.get(`${r},${c}`)) c += 1;
        for (let dr = 0; dr < cell.rowspan; dr++) for (let dc = 0; dc < cell.colspan; dc++) {
          occupied.set(`${r + dr},${c + dc}`, true);
          (grid[r + dr] ??= [])[c + dc] = cell.text;
        }
        c += cell.colspan;
      }
    });
    const nCols = Math.max(0, ...grid.map((g) => g.length));
    const headerRows = rowsRaw.map((r, i) => (r.inHead ? i : -1)).filter((i) => i >= 0);
    const headers = Array.from({ length: nCols }, (_x, c) => headerRows.map((r) => grid[r]?.[c]).filter(Boolean).join(" / "));
    const rows = rowsRaw
      .map((r, i) => ({ r, i }))
      .filter(({ r }) => !r.inHead)
      .map(({ i }) => (grid[i] ?? []).map((text, c) => ({ text, header: headers[c] ?? "" })));
    tables.push({ figure: fig, caption, headers, rows });
  }
  return tables;
}

