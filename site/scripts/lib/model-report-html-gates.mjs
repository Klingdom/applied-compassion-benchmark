/** G6. `requireReport`: a report route must carry one Report node. */
export function ratingSchemaProblems(html, { requireReport = false } = {}) {
  const p = [];
  const blocks = extractJsonLd(html);
  const types = [];
  for (const b of blocks) {
    walk(b, (o) => {
      if (o["@parseError"]) p.push(`G6-parse: JSON-LD does not parse: ${o["@parseError"]}`);
      for (const t of [].concat(o["@type"] ?? [])) types.push(t);
      for (const k of FORBIDDEN_LD_KEYS) if (k in o) p.push(`G6-key: JSON-LD carries "${k}" (ratings and composites never enter structured data)`);
    });
  }
  for (const t of types) if (FORBIDDEN_LD_TYPES.includes(t)) p.push(`G6-type: forbidden JSON-LD type "${t}"`);
  if (requireReport && !types.includes("Report")) p.push("G6-missing: no Report node in the JSON-LD of a report route");
  if (requireReport && types.filter((t) => t === "Report").length > 1) p.push("G6-multiple: more than one Report node");
  return p;
}

/** G5. The unofficial banner is a role="region" element, first in <main>, before the H1 text. */
export function bannerProblems(html) {
  const p = [];
  const main = html.match(/<main\b[^>]*>/i);
  if (!main) return ["G5-main: no <main> element"];
  const rest = html.slice(main.index + main[0].length);
  const region = rest.match(/<(\w+)\b[^>]*role=["']region["'][^>]*>([\s\S]*?)<\/\1>/i);
  if (!region) return ["G5-banner: no role=\"region\" banner in <main>"];
  const h1 = rest.search(/<h1\b/i);
  if (h1 >= 0 && h1 < region.index) p.push("G5-order: the banner comes after the H1; it must be first in <main>");
  const firstElement = rest.match(/<(\w+)\b[^>]*>/);
  if (firstElement && firstElement.index < region.index && !/^<(?:script|style|link|meta)\b/i.test(firstElement[0]) && firstElement[0] !== region[0].match(/<(\w+)\b[^>]*>/)[0]) {
    p.push(`G5-first: the first element in <main> is ${firstElement[0].slice(0, 40)}, not the status banner`);
  }
  if (!/unofficial/i.test(region[2])) p.push("G5-text: the banner does not say \"unofficial\"");
  if (!/not a ranking/i.test(region[2])) p.push("G5-text: the banner does not say \"not a ranking\"");
  if (!/no cross-model comparison/i.test(region[2])) p.push("G5-text: the banner does not say \"no cross-model comparison\"");
  if (!/aria-label=["'][^"']+["']/i.test(region[0].match(/<\w+\b[^>]*>/)[0])) p.push("G5-label: the banner region has no accessible name (aria-label)");
  if (/position\s*:\s*sticky|sticky/i.test(region[0].slice(0, 300))) p.push("G5-sticky: the banner is sticky (it obscures focus, SC 2.4.11)");
  return p;
}

/** The founder-preview strip: present, a note, says PREVIEW and not approved. */
export function previewStripProblems(html) {
  const m = html.match(/<(\w+)\b[^>]*role=["']note["'][^>]*>([\s\S]*?)<\/\1>/i);
  if (!m || !/PREVIEW/.test(m[2]) || !/not approved for publication/i.test(m[2])) return ["G5-preview: a proposed (not ratified) wave renders without the visible \"PREVIEW — not approved for publication\" strip"];
  return [];
}

