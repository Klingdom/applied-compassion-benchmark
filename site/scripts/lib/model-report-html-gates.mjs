/**
 * model-report-html-gates.mjs -- HTML-level gates (template I: G5, G6, G19, G20)
 * over BUILT pages (site/out/ai-models/** and ai-models.html).
 *
 * Pure functions of an HTML string, a wave object or a directory path, so each is
 * proved with a planted probe (test-model-report-html.mjs, test-model-html-leak.mjs,
 * test-model-report-seo.mjs) and then pointed at the real built tree.
 *
 *   G5   bannerProblems            unofficial banner: labelled region, first in <main>, not sticky
 *   G6   ratingSchemaProblems      no Review/Rating/Dataset/ItemList/... JSON-LD, no rating keys
 *   --   treeProblems              the gate itself: default build emits NO report HTML and no pilot
 *                                  wording; a preview or ratified build emits exactly the rendered reports
 *   G19  leakProblems              withheld values never reach a page (see below)
 *   G20  seoProblems               title / meta / canonical / JSON-LD rules of template G
 *   H    ctaProblems               no paid CTA inside the report article
 *
 * HTML is parsed with small regular expressions: the pages are generated by this repo's own
 * components, so the shapes are known. Where a rule needs table context (which column a number
 * sits under) a real header grid is built (colspan and rowspan honoured).
 */

