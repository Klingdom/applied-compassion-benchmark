const numTok = (v, d = 1) => v.toFixed(d);
const tokRe = (tok) => new RegExp(`(?<![0-9])${escRe(tok)}(?![0-9])`);
const BARE_NUM = /^[−-]?\d+\.\d+$/;

/**
 * Values an unratified or restricted page must not show, derived from the wave only.
 *  composites     point estimates of every subject (group members: never; separated: only in a
 *                 table cell under a "Point estimate" header)
 *  bounds         length-removed values (only beside "not an estimate" / "extreme bound")
 *  diffs          point differences of not-separated pairs (never)
 */
export function withheldValues(wave) {
  const sep = new Set(wave.derived.separated_subjects);
  const subjects = wave.design.subjects;
  const members = subjects.filter((id) => !sep.has(id));
  const composites = (ids) => ids.flatMap((id) => [numTok(wave.subjects[id].pilot_composite), ...(wave.sensitivity?.subjects?.[id] ? [numTok(wave.sensitivity.subjects[id].pilot_composite)] : [])]);
  const intervalEnds = (ids) => ids.flatMap((id) => wave.subjects[id].pilot_composite_interval95.map((v) => numTok(v)));
  return {
    sep,
    members,
    memberComposites: [...new Set(composites(members))],
    separatedComposites: [...new Set(composites(wave.derived.separated_subjects))],
    allComposites: [...new Set(composites(subjects))],
    allIntervalEnds: [...new Set(intervalEnds(subjects))],
    bounds: [...new Set(Object.values(wave.length.composite_if_pooled_slope_removed).map((v) => numTok(v)))],
    unseparatedPairs: wave.pairwise.filter((q) => !q.separated).map((q) => ({ a: q.a, b: q.b, tok: numTok(q.difference) })),
    memberDimMeans: [...new Set(members.flatMap((id) => Object.values(wave.subjects[id].dimensions).map((v) => numTok(v, 2))))],
  };
}

/**
 * G19. `kind`:
 *   "report"  the report route of this wave
 *   "index"   any other /ai-models/** page while this wave renders: no per-model figure at all
 */
export function leakProblems({ html, wave, kind }) {
  const p = [];
  const w = withheldValues(wave);
  const naming = makeNaming(wave);
  const tables = parseTables(html);
  const restHtml = html.replace(/<table\b[\s\S]*?<\/table>/gi, "");
  const units = [
    ...textBlocks(restHtml).map((text) => ({ text, kind: "text" })),
    ...attributeTexts(html).map((text) => ({ text, kind: "attr" })),
    ...jsonLdStrings(extractJsonLd(html)).map((x) => ({ text: x.text, kind: "jsonld" })),
  ];
  const cells = tables.flatMap((t) => t.rows.flatMap((row) => row.map((c) => ({ text: c.text, kind: "cell", header: c.header, figure: t.figure, row, caption: t.caption }))));
  const all = [...units, ...cells];
  const where = (u) => (u.kind === "cell" ? `table cell "${u.text.slice(0, 40)}" (column "${u.header.slice(0, 50)}")` : `${u.kind} "${u.text.slice(0, 70)}"`);

  // L1: group members' composites never appear, in any form.
  for (const tok of w.memberComposites) for (const u of all) if (tokRe(tok).test(u.text)) p.push(`G19-member-composite: ${tok} (a not-separated model's point estimate) in ${where(u)}`);

  if (kind === "report") {
    // L2: a separated model's point only in a cell under a "Point estimate" header.
    for (const tok of w.separatedComposites) for (const u of all) {
      if (!tokRe(tok).test(u.text)) continue;
      if (u.kind === "cell" && /point estimate/i.test(u.header) && BARE_NUM.test(u.text)) continue;
      p.push(`G19-point-outside-cell: ${tok} (a separated model's point estimate) in ${where(u)}, not in a "Point estimate" table cell`);
    }
    // L3: the length-removed bound only beside "not an estimate" / "extreme bound".
    for (const tok of w.bounds) for (const u of all) {
      if (!tokRe(tok).test(u.text)) continue;
      if (u.kind === "cell" && /extreme bound/i.test(u.header)) continue;
      if (u.kind !== "cell" && /not an estimate|extreme bound/i.test(u.text)) continue;
      p.push(`G19-bound-unlabelled: ${tok} (the length-removed bound) in ${where(u)} without "not an estimate" / "extreme bound"`);
    }
    // L4: point differences of not-separated pairs, in a pair's row or beside both names.
    for (const q of w.unseparatedPairs) {
      for (const t of tables) for (const row of t.rows) {
        const rowText = row.map((c) => c.text).join(" | ");
        if (rowText.includes(q.a) && rowText.includes(q.b) && row.some((c) => BARE_NUM.test(c.text) && c.text.replace(/^[\u2212-]/, "") === q.tok)) p.push(`G19-unseparated-difference: ${q.tok} (point difference of ${q.a} / ${q.b}, a not-separated pair) in a table row`);
      }
      // Prose: "A minus B ... <tok>" or "difference between A and B ... <tok>". A bare token elsewhere in a block that
      // happens to name both models (a slope list, say) is a different number and is not flagged.
      const pairForms = [`${escRe(q.a)} minus ${escRe(q.b)}`, `${escRe(q.b)} minus ${escRe(q.a)}`, `difference between ${escRe(q.a)} and ${escRe(q.b)}`, `difference between ${escRe(q.b)} and ${escRe(q.a)}`];
      const proseRe = new RegExp(`(?:${pairForms.join("|")})[^\\n]{0,50}?(?<![0-9])${escRe(q.tok)}(?![0-9])`);
      for (const u of units) if (proseRe.test(u.text)) p.push(`G19-unseparated-difference: ${q.tok} (point difference of ${q.a} / ${q.b}) beside the pair in ${where(u)}`);

    }
    // L6: dimension means of group members never appear in the dimension figure's table.
    for (const t of tables.filter((x) => x.figure === "fig-dimensions")) for (const row of t.rows) for (const c of row) {
      if (BARE_NUM.test(c.text) && w.memberDimMeans.includes(c.text) && w.members.some((id) => c.header.includes(id))) p.push(`G19-member-dimension-mean: ${c.text} (a not-separated model's mean) in the dimension table under "${c.header.slice(0, 50)}"`);
    }
  } else {
    // L7: no per-model figure at all outside the report.
    for (const tok of [...w.allComposites, ...w.allIntervalEnds, ...w.bounds]) for (const u of all) if (tokRe(tok).test(u.text)) p.push(`G19-index-figure: ${tok} (a per-model figure) in ${where(u)} on a page that is not the report`);
  }

  // L5: no band name beside a model name (same block, or same table row).
  const rowUnits = tables.flatMap((t) => t.rows.map((row) => ({ text: row.map((c) => c.text).join(" | "), kind: "row" })));
  for (const u of [...all, ...rowUnits]) {
    if (!naming.mentions(u.text).length) continue;
    for (const band of BAND_NAMES) if (new RegExp(`\\b${band}\\b`).test(u.text)) p.push(`G19-band-beside-model: band "${band}" beside a model name in ${where(u)}`);
  }
  return p;
}

